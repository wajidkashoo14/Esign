// Generates prisma/postgres/schema.prisma from prisma/schema.prisma (provider swap).
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

const src = readFileSync("prisma/schema.prisma", "utf8");
let out = src
  .replace(/^\/\/ Local default[\s\S]*?\n\n/, "// GENERATED by `npm run db:sync-pg` from prisma/schema.prisma. Do not edit.\n\n")
  .replace(
    /provider = "sqlite"\n\s*url\s*=\s*env\("DATABASE_URL"\)/,
    'provider  = "postgresql"\n  url       = env("DATABASE_URL")\n  directUrl = env("DIRECT_URL")',
  );
if (out === src) throw new Error("schema transform failed");
mkdirSync("prisma/postgres", { recursive: true });
writeFileSync("prisma/postgres/schema.prisma", out);
console.log("wrote prisma/postgres/schema.prisma");
